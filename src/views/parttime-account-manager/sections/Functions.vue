      <div id="schedule" class="module card">
        <h3>1.1 排班排假</h3>
        <p><strong>模块目标：</strong>维护门店每周重复的任务需求。页面只回答“什么门店、哪一天、什么时段、需要几个人”，不指定具体承接人，也不负责手工发布。</p>
        <h4>页面结构</h4>
        <ol><li>顶部：城市、门店、有效状态和关键字筛选。</li><li>主体：按星期展示每日时段需求，可在同一门店下维护多个时段。</li><li>操作区：新增、编辑、作废、导入、导出。</li></ol>
        <h4>字段与规则</h4>
        <table class="data-table"><thead><tr><th>字段</th><th>业务定义</th><th>校验/生效规则</th></tr></thead><tbody>
          <tr><td>城市、门店</td><td>需求归属的经营单位</td><td>新增门店先按城市筛选；门店只能归属一个城市</td></tr>
          <tr><td>星期</td><td>周一至周日的重复需求</td><td>每天独立配置，不能用一条记录隐含多天</td></tr>
          <tr><td>开始/结束时间</td><td>任务计划服务时段</td><td>结束时间晚于开始时间；单段最长 4 小时</td></tr>
          <tr><td>名额</td><td>该时段需要的人数</td><td>正整数；生成时一个名额对应一个任务实例</td></tr>
          <tr><td>生效日期</td><td>规则开始参与生成的日期</td><td>只影响尚未生成的未来周期</td></tr>
          <tr><td>备注</td><td>运营说明和业务背景</td><td>不作为长期、短期、临时的强制分类条件</td></tr>
          <tr><td>状态</td><td>有效/已作废</td><td>删除动作统一称“作废”；历史记录可查</td></tr>
        </tbody></table>
        <h4>操作流程与边界</h4>
        <ul><li>新增或编辑后，系统校验同门店同星期的时间重叠、名额格式和日期范围。</li><li>作废配置后，不再参与新的定时发布；已生成或已承接任务不回收、不改写。</li><li>导入按城市、门店、星期、时段、名额、生效日期和备注校验；错误行给出行号和原因。</li><li>导出只导出当前筛选范围的配置，不导出任务承接和人员信息。</li></ul>
