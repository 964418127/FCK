    <div id="income" class="section">
      <h2>三、收入配置模块</h2>
      <p>本模块维护非全客户经理的保底金额和三项收入单价。任务生成、抢选和派发不读取收入配置；任务实际完成后，薪酬模块以<strong>实际承接人、任务所属门店、服务时间</strong>读取对应配置。人员可服务多家门店，沿用现有薪酬口径：<strong>1 门店 = 1 结算主体</strong>，按人员与门店分别归集，不把不同门店的收入或保底合并。</p>

      <div id="income-prices" class="module card">
        <h3>3.1 收入单价配置</h3>
        <p><strong>业务目的：</strong>为新客、评价、客次三个计价项目分别确定单价。每个项目独立判断覆盖与继承，个人配置的归属键是<strong>人员 ID + 门店 ID</strong>，不是人员 ID；同一人在不同门店可有不同单价。</p>
        <h4>页面结构与查询</h4>
        <table class="data-table"><thead><tr><th>区域</th><th>展示与操作</th><th>交互要求</th></tr></thead><tbody>
          <tr><td>顶部通用配置</td><td>新客、评价、客次三个通用单价和编辑入口</td><td>进入页面直接可见；三项均必须有值；不允许作废</td></tr>
          <tr><td>城市列</td><td>城市搜索、城市配置列表、新增/编辑/作废</td><td>每项同时显示解析后金额及“本级配置”或“继承通用”</td></tr>
          <tr><td>门店列</td><td>按名称、编号、城市搜索；门店配置列表和操作</td><td>新增时先选城市，再从该城市门店中选择；每项标明本级或继承来源</td></tr>
          <tr><td>个人列</td><td>按工号或姓名搜索，按人归组展示各门店关系</td><td>每家门店独立展示三项解析金额、来源和编辑/作废</td></tr>
        </tbody></table>
        <h4>配置字段与校验</h4>
        <table class="data-table"><thead><tr><th>字段</th><th>配置要求</th><th>数据约束</th></tr></thead><tbody>
          <tr><td>配置层级、归属</td><td>通用；城市 ID；门店 ID；人员 ID + 门店 ID</td><td>城市和门店来自主数据；同层级同归属最多一条有效记录；编辑时归属不可改</td></tr>
          <tr><td>人员、工号</td><td>个人配置先以工号或姓名选择非全客户经理</td><td>保存人员 ID；姓名、工号仅供查询展示，不作为唯一键</td></tr>
          <tr><td>门店城市</td><td>门店新增时先选择城市筛选门店</td><td>保存门店 ID；展示城市、门店名称和编号；个人配置也绑定具体门店</td></tr>
          <tr><td>新客单价</td><td>新客计价事件每次对应的单价</td><td>人民币元；非负数，最多两位小数；0 是有效覆盖值</td></tr>
          <tr><td>评价单价</td><td>有效评价事件每次对应的单价</td><td>同上</td></tr>
          <tr><td>客次单价</td><td>有效服务客次每次对应的单价</td><td>同上</td></tr>
          <tr><td>单独配置开关</td><td>决定当前层级是否覆盖该项目</td><td>通用三项全部配置；其他层级至少勾选一项。未勾选不存金额，自动继承</td></tr>
          <tr><td>状态、作废时间</td><td>有效或已作废及操作时间</td><td>系统写入；已作废记录可查，不参与新收入解析</td></tr>
        </tbody></table>
        <h4>新增、编辑与作废</h4>
        <ol>
          <li>新增城市、门店或个人配置可独立进行，不要求上一级已经配置。新增城市从未配置城市选择；新增门店先选城市再选门店；新增个人先选人员，再选其服务门店。保存时至少单独配置一项。</li>
          <li>编辑时可勾选项目并填写金额，也可取消勾选。取消勾选表示移除该项目的本级覆盖，下次读取即继承上一级；不能把“继承”误存为当前显示的金额。若三项均取消，提示作废该条配置。</li>
          <li>作废城市配置只使该城市本级三项失效，不联动作废门店或个人配置；作废门店也不联动作废个人配置。各项目继续沿剩余有效层级解析。作废个人×门店配置后，该人在该门店全部项目回退到门店/城市/通用。</li>
          <li>作废二次确认并保留历史记录；同一归属后续可重新新增。历史已结算明细使用当时配置快照，不被后续改价或作废重算。</li>
        </ol>
        <h4>逐项解析规则</h4>
